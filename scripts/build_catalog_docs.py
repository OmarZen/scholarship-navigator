#!/usr/bin/env python3
"""
Generate browsable catalogue pages from the data files:

  docs/SCHOLARSHIPS.md   every scholarship: country, degrees, funding, who can apply, deadline, status
  docs/PROGRAMS.md       every Erasmus Mundus / Intra-Africa program: field, where you study, status, deadline

Usage:  python scripts/build_catalog_docs.py          write the pages
        python scripts/build_catalog_docs.py --check  exit 1 if they are out of date
"""

import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from planner.matcher import load_scholarships  # noqa: E402
from planner.programs import load_programs  # noqa: E402
from planner.regions import group_title  # noqa: E402

DOCS = REPO / "docs"
GROUP_TITLES = {
    "computing": "Computing, AI & data", "engineering": "Engineering", "natural_sciences": "Natural sciences",
    "health": "Health & biomedical", "agriculture": "Agriculture & food", "environment": "Environment & energy",
    "economics_business": "Economics & business", "social_sciences": "Social sciences", "humanities": "Humanities & arts",
}
STATUS_LABEL = {"open": "✅ open", "upcoming": "🕒 upcoming", "self_funded_only": "💶 self-funded only",
                "discontinued": "❌ discontinued", "unknown": "❓ unknown"}


def cell(x) -> str:
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def who_can_apply(s) -> str:
    nat = s.rules.nationality
    if nat.mode == "any":
        return "All nationalities"
    if nat.mode == "exclude":
        excluded = nat.exclude_countries + [group_title(r) for r in nat.exclude_regions]
        return "All except " + ", ".join(excluded)
    parts = [group_title(r) for r in nat.regions]
    if nat.countries:
        parts.append(f"{len(nat.countries)} listed countries")
    return ("Only " if nat.mode == "include" else "Check list: ") + " + ".join(parts or ["listed countries"])


def deadline_text(est, intake=2027) -> str:
    if not est:
        return "see site"
    known = est.known_dates.get(str(intake))
    if known:
        return known
    return f"~{est.month:02d}-{est.day:02d} (usual)"


def scholarships_page() -> str:
    rows = []
    for s in sorted(load_scholarships(include_custom=False), key=lambda x: x.name.lower()):
        rows.append(f"| [{cell(s.name)}]({s.official_portal}) | {cell(s.country)} | {', '.join(s.degrees)} | "
                    f"{s.funding_type} | {cell(who_can_apply(s))} | {deadline_text(s.timeline.deadline)} | "
                    f"{s.program_status} | {s.data_last_reviewed or '-'} |")
    return ("# Scholarships in the database\n\n_Generated by `scripts/build_catalog_docs.py` from "
            "`data/scholarships.json`. Deadlines are for the 2027 intake; \"(usual)\" means the yearly pattern, not a "
            "confirmed date. Always check the official site._\n\n"
            "| Scholarship | Country | Degrees | Funding | Who can apply | Deadline (2027 intake) | Status | Reviewed |\n"
            "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")


def programs_page() -> str:
    programs = load_programs()
    by_group = defaultdict(list)
    for p in programs:
        by_group[(p.field_groups or ["engineering"])[0]].append(p)
    out = ["# Programs inside scholarship schemes", "",
           "_Generated by `scripts/build_catalog_docs.py` from `data/programs/`. Erasmus Mundus Joint Masters are "
           "open to all nationalities (up to 3 applications per year); Intra-Africa projects are for African nationals. "
           "Find the ones that fit a profile with `cli.py programs`._", "",
           f"**{len(programs)} programs** · " + " · ".join(
               f"{label}: {sum(1 for p in programs if p.status == key)}" for key, label in STATUS_LABEL.items()), ""]
    for group in sorted(by_group, key=lambda g: GROUP_TITLES.get(g, g)):
        out += [f"## {GROUP_TITLES.get(group, group)}", "",
                "| Program | Where you study | Status | Deadline (2027 intake) | English | Verified |",
                "|---|---|---|---|---|---|"]
        for p in sorted(by_group[group], key=lambda x: x.acronym.lower()):
            out.append(f"| [**{cell(p.acronym)}**]({p.website}): {cell(p.name)} | {cell(', '.join(p.host_countries)) or '-'} | "
                       f"{STATUS_LABEL[p.status]} | {deadline_text(p.deadline)} | {cell(p.english_requirement or '-')} | "
                       f"{p.verified_on or '-'} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    pages = {DOCS / "SCHOLARSHIPS.md": scholarships_page(), DOCS / "PROGRAMS.md": programs_page()}
    if "--check" in sys.argv:
        stale = [p for p, text in pages.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"out of date: {p.relative_to(REPO)}")
        return 1 if stale else 0
    DOCS.mkdir(exist_ok=True)
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
